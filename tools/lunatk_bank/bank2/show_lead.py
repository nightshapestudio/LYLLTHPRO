"""SHOWCASE LEADS: mono voices with a present, centred core. Width, when a
lead has it, is added after the transient or held in a separate upper layer.
Velocity, mod wheel and pressure all do something; effects stay behind the note."""

from lunatk import Preset
from bank2._common import echo, grit, space, velocity, vibrato
from bank2._showcase import dimension, drift, fsat, morph, punch, vintage


def L(name, a="ANALOG", b="BASIC"):
    return Preset(name, "LEAD", a, b)


def mono(p, glide=0.035, legato=True, bend=2, vel=0.4):
    return p.voice(voices=1, glide=glide, legato=legato, glide_always=False, vel=vel, bend=bend)


def room(p, mix=0.1, decay=0.3, amount=0.12):
    return space(p, mix, mode="PLATE", size=0.45, decay=decay, damp=0.5, predelay=0.06, width=0.8, amount=amount)


