import math

from lunatk import Preset
from bank._common import echo, grit, space, velocity


def K(name, a="ANALOG", b="BASIC"):
    return Preset(name, "PLUCK", a, b)


def pluck_voice(p, vel=0.7):
    return p.voice(voices=10, glide=0.0, vel=vel, bend=2)


def room(p, mix=0.14, decay=0.28, amount=0.18):
    return space(p, mix, mode="PLATE", size=0.4, decay=decay, damp=0.55, predelay=0.06, width=0.75, amount=amount)


# Comb cutoff that puts the comb's pitch on the played note (keytrack 1).
COMB_TUNED = math.log(261.63 / 20.0) / math.log(1000.0)


def string(p, ring=0.9, burst=0.02, color=0.35, noise="WHITE"):
    """A noise burst exciting a key-tracked comb: a plucked string."""
    p.noise(0.0, noise, color=color, keytrack=False)
    p.env(4, a=0.0005, d=burst, s=0.0, r=burst)
    p.mod("ENV4", "NOISE_LEVEL", 1.0)
    p.filter("COMB_POS", cut=COMB_TUNED, res=ring, keytrack=1.0, mix=1.0)
    return p


